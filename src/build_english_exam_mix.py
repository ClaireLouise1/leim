#!/usr/bin/env python3
"""Build the English Exam Mix question bundles (Order 32) from the other JC English games.

Same idea as the Maths Exam Mix (src/build_exam_mix.py, whose helpers it imports): for every game in SECTIONS
it takes the question makers from src/<slug>.script.html (inside the closure, up to the "Game loop" comment)
and registers them on window.LEIM_EN[slug] = {M: {<mode>: [...], mixed: [...]}, orders: [FIXED, PERMS, MARKS…], pu}.
orders = the game's own fixed button orders (its loop sorts label buttons into the first that holds every option);
pu = the game's punctuation renderer for option buttons (Comma Catch, Speech Marks Sprint, Proofread Patrol).
Each game's <style> block is scoped to .gx-<slug>; the Exam Mix page puts that class on the frame.

Writes english-exam-mix-<section>.js in the repo root (loaded by english-exam-mix.html only when needed).
Re-run after ANY change to an English game's makers or styles:  python3 src/build_english_exam_mix.py
Then: N=40 node src/test_english_exam_mix_bundles.js && python3 src/check_english_exam_mix_bundles.py
"""
import os, json, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_exam_mix import scope, makers_section, styles, title, ROOT

# grouped like the paper: reading (unseen texts), writing (your own texts), studied texts, language & accuracy
SECTIONS = {
    "reading": ["clue-hunt", "fact-or-opinion", "ad-breaker", "pqe-builder"],
    "writing": ["paragraph-builder", "show-dont-tell", "story-spine", "format-fixer", "register-switch",
                "persuasion-power", "format-sort", "talk-tips"],
    "texts": ["character-clues", "technique-spotter", "twist-detector", "plot-line", "stage-it", "mood-match",
              "shot-spotter", "who-said-it", "compare-cards"],
    "language": ["word-sort", "sentence-surgeon", "comma-catch", "spell-strike", "word-ladder", "tense-trap",
                 "speech-marks-sprint", "proofread-patrol"],
}


def build(sec, slugs):
    names = {s: title(s) for s in slugs}
    parts = ["/* Léim English Exam Mix bundle: %s. GENERATED by src/build_english_exam_mix.py from the games' src files - do not edit. */\n" % sec,
             "window.LEIM_EN=window.LEIM_EN||{};window.LEIM_EN_GAMES=window.LEIM_EN_GAMES||{};\n",
             "(function(n){for(var k in n)LEIM_EN_GAMES[k]=n[k];})(%s);\n" % json.dumps(names, ensure_ascii=False)]
    css = []
    for slug in slugs:
        parts.append("LEIM_EN[%s]=(function(){\n%s\n  var _all=[];Object.keys(MAKERS).forEach(function(k){(MAKERS[k]||[]).forEach(function(f){if(_all.indexOf(f)<0)_all.push(f);});});\n"
                     "  if(!MAKERS.mixed||!MAKERS.mixed.length)MAKERS.mixed=_all;\n  function _d(x){return typeof x!==\"undefined\"?x:null;}\n  var _o=[_d(typeof FIXED!==\"undefined\"?FIXED:undefined),_d(typeof PERMS!==\"undefined\"?PERMS:undefined),_d(typeof MARKS!==\"undefined\"?MARKS:undefined),(typeof NAME!==\"undefined\"&&typeof lab===\"function\")?Object.keys(NAME).map(lab):null].filter(function(a){return a&&a.length;});\n  return {M:MAKERS,orders:_o,pu:(typeof pu===\"function\"?pu:null)};\n})();\n"
                     % (json.dumps(slug), makers_section(slug)))
        c = scope(styles(slug), "gx-" + slug)
        if c:
            css.append(c)
    parts.append("(function(){if(!document.head||!document.head.appendChild)return;var s=document.createElement('style');s.textContent=%s;document.head.appendChild(s);})();\n"
                 % json.dumps("".join(css), ensure_ascii=False))
    out = "".join(parts)
    p = os.path.join(ROOT, "english-exam-mix-%s.js" % sec)
    open(p, "w", encoding="utf-8").write(out)
    print("wrote", os.path.basename(p), len(out.encode("utf-8")), "bytes,", len(slugs), "games")


if __name__ == "__main__":
    allg = [s for v in SECTIONS.values() for s in v]
    assert len(allg) == len(set(allg)) == 29, len(allg)
    for k, v in SECTIONS.items():
        build(k, v)
