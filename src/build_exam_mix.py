#!/usr/bin/env python3
"""Build the Exam Mix question bundles (Order 38) from the other JC Maths games.

For every game in STRANDS it takes the question makers from src/<slug>.script.html
(everything inside the page's closure up to the "Game loop" comment) and wraps them
so they register on window.LEIM_MAKERS[slug] = {mixed:[...], <mode>:[...]}.
Each game's own <style> block (from src/<slug>.main.html) is scoped to .gx-<slug>
so pictures look the same as in the game; the Exam Mix page puts that class on the frame.

Writes exam-mix-<strand>.js in the repo root (loaded by exam-mix.html only when needed).
Re-run after ANY change to a game's makers or styles:  python3 src/build_exam_mix.py
"""
import os, re, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")

STRANDS = {
    "number": ["integer-rush", "prime-smash", "fraction-match", "round-it", "venn-sorter",
               "percent-pop", "share-it-out", "clock-dash", "power-up", "shop-keeper",
               "payslip-puzzle", "road-trip", "surd-simplify"],
    "algebra": ["like-term-sweep", "pattern-builder", "bracket-blaster", "balance-it",
                "factor-match", "two-line-crossing", "root-rush", "graph-match",
                "number-line-shade", "rearrange-race", "growth-spotter"],
    "geometry": ["angle-chase", "construction-steps", "floor-planner", "mirror-move",
                 "proof-builder", "ladder-lab", "line-lab", "clinometer-challenge", "pack-it"],
    "stats": ["spin-and-predict", "data-detective", "average-ace", "coin-dice-lab"],
}


def split_rules(css):
    """Split CSS into top-level (prelude, body) pairs."""
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            break
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        out.append((css[i:j].strip(), css[j + 1:k - 1]))
        i = k
    return out


def scope(css, cls):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    res = []
    for pre, body in split_rules(css):
        if pre.startswith("@media") or pre.startswith("@supports"):
            res.append(pre + "{" + scope(body, cls) + "}")
        elif pre.startswith("@"):
            res.append(pre + "{" + body + "}")
        else:
            sels = []
            for s in pre.split(","):
                s = s.strip()
                if not s:
                    continue
                if re.match(r"^(html|body|:root)\b", s):
                    continue
                sels.append("." + cls + " " + s)
            if sels:
                res.append(",".join(sels) + "{" + body.strip() + "}")
    return "".join(res)


def makers_section(slug):
    t = open(os.path.join(SRC, slug + ".script.html"), encoding="utf-8").read()
    a = t.index("(function(){") + len("(function(){")
    b = t.index("/* ---------- Game loop")
    return t[a:b]


def styles(slug):
    t = open(os.path.join(SRC, slug + ".main.html"), encoding="utf-8").read()
    return "".join(re.findall(r"<style[^>]*>(.*?)</style>", t, flags=re.S))


def title(slug):
    t = open(os.path.join(SRC, slug + ".main.html"), encoding="utf-8").read()
    h = re.search(r"<h1[^>]*>(.*?)</h1>", t, flags=re.S).group(1)
    return re.sub(r"<[^>]+>", "", h).replace("&amp;", "&").strip()


def build(strand, slugs):
    names = {s: title(s) for s in slugs}
    parts = ["/* Léim Exam Mix bundle: %s. GENERATED by src/build_exam_mix.py from the games' src files - do not edit. */\n" % strand,
             "window.LEIM_MAKERS=window.LEIM_MAKERS||{};window.LEIM_GAMES=window.LEIM_GAMES||{};\n",
             "(function(n){for(var k in n)LEIM_GAMES[k]=n[k];})(%s);\n" % json.dumps(names, ensure_ascii=False)]
    css = []
    for slug in slugs:
        sec = makers_section(slug)
        parts.append("LEIM_MAKERS[%s]=(function(){\n%s\n  var _all=[];Object.keys(MAKERS).forEach(function(k){(MAKERS[k]||[]).forEach(function(f){if(_all.indexOf(f)<0)_all.push(f);});});\n  if(!MAKERS.mixed||!MAKERS.mixed.length)MAKERS.mixed=_all;\n  return MAKERS;\n})();\n" % (json.dumps(slug), sec))
        c = scope(styles(slug), "gx-" + slug)
        if c:
            css.append(c)
    allcss = "".join(css)
    parts.append("(function(){var s=document.createElement('style');s.textContent=%s;document.head.appendChild(s);})();\n" % json.dumps(allcss, ensure_ascii=False))
    out = "".join(parts)
    p = os.path.join(ROOT, "exam-mix-%s.js" % strand)
    open(p, "w", encoding="utf-8").write(out)
    print("wrote", os.path.basename(p), len(out.encode("utf-8")), "bytes,", len(slugs), "games")


if __name__ == "__main__":
    for k, v in STRANDS.items():
        build(k, v)
